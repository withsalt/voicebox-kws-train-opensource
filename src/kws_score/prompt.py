"""把 wakeword-score 技能的评分细则编码为大模型 prompt。

系统提示词承载评分规则与分工：客观维度(A/E/建模硬扣分/拼音)已由脚本确定性算好，
模型只需用世界知识最终敲定 C(误唤醒)、在 B/D 缺失时补全，并产出文字分析。
"""

from __future__ import annotations

import json

from .schema import TOOL_NAME

SYSTEM_PROMPT = """\
你是中文语音唤醒词(KWS)评分专家，针对阿里 speech_charctc_kws_phone 系列近场唤醒模型校准。

# 模型特性（评分依据）
- 网络：4 层 cFSMN，约 750K 参数，面向移动端/近场，16k 单通道。
- 建模：char-based CTC，输出中文字符 token；token 表约 2599 项，其中**中文单字仅约 1673 个**，生僻字会 OOV。
- 经验最优形态：**4 音节叠词**（如 小云小云 / 小度小度），易检测、自然语流中罕见、误唤醒低。
- 训练要求（给建议时引用）：中文音频 + 全文逐字标注；正样本 ≥25 小时、正:负 1:2~1:10；训练仅支持 Linux+GPU；误唤醒可上调 keywords.json 的 threshold1 压制。

# 评分细则（满分 100）
| 维度 | 权重 | 衡量 | 评分要点 |
|---|---|---|---|
| A 音节数 | 20 | 长度 | 4=20(最佳)；5=16；3或6=12；2=5；1/超长=低。<3 音节误唤醒显著升高。|
| B 音素区分度 | 20 | 声韵母丰富度 | (不同声母数+不同韵母数)/(2×音节数)×20。叠词天然偏低属正常，由 C 的叠词信心补偿。|
| C 误唤醒风险 | 30 | 是否易被日常语音误触发 | **最重要、需世界知识**。常用词/人名/产品词命中→重扣；叠词整体罕见→加分；务必评估连呼场景。0–30。|
| D 发音清晰度 | 15 | 好不好读 | 声调单一−5、仅两种−1；连续≥3同声母−3、全同−5；含轻声每个−2(封顶−4)。|
| E 建模可行性 | 15 | 该模型能否建模 | 含非中文字符或 OOV 字→维度内每字−8 至 0。|

# 分工（重要）
脚本已**确定性**算好这些，你**必须直接采用、不得改动**：A 音节数、E 建模可行性、是否含不可建模字符、建模硬扣分、拼音、叠词结构。你的职责仅是：
1. **C 误唤醒风险（核心）**：脚本给的 C 只是启发式线索值。你必须用世界知识最终定分：
   - 该词或其叠词**基本单元**/子串是否为高频常用词、常见人名/宠物名/称呼、现有产品唤醒词？是→大幅扣分。
   - 是否与常用词近音（易误触发）？
   - 叠词整体(如 ABAB)在自然连续语流中极少出现，应据此加回信心；但要专门评估**连续呼叫**场景：若基本单元是人名/宠物名，有人连叫两声会非常接近完整唤醒词。
2. **B / D**：若 metrics 已给出非 null 值，**原样照抄**；仅当为 null（缺 pypinyin）时，用你的普通话拼音知识按上表自算。
3. 产出各维度一句话理由、误唤醒详细分析、关键风险、训练/落地建议；若最终分 <55 或风险高，给 2–3 个更优替代候选。

> 注：近音正样本词**不需要你产出**——由脚本从唤醒词拼音确定性计算（仅声调/模糊音差异、排除完全同音），并在第三步统一标注为目标唤醒词。负样本亦另行处理。

# 总分与等级（由调用方按规则计算，你无需自己加总）
final = max(0, A+B+C+D+E − 40×[含任一不可建模字符])。等级：≥85 优秀｜70–84 良好｜55–69 合格｜<55 不推荐。
注意：叠词在 B 维度天然偏低但仍是好形态，其价值体现在 C；不要因 B 偏低就否定一个 4 音节叠词。

只能通过调用 `%s` 工具输出结果，禁止输出工具之外的任何文字。results 数组必须与输入候选词一一对应、顺序一致。\
""" % TOOL_NAME


def build_user_content(metrics_list: list[dict]) -> str:
    """把每个候选词的客观指标整理成发给模型的用户内容。"""
    words = [m["word"] for m in metrics_list]
    lines = [
        f"请为以下 {len(words)} 个候选唤醒词评分：{' / '.join(words)}",
        "",
        "下面是脚本已确定性算好的客观指标（A/E/建模硬扣分/拼音/叠词请直接采用；"
        "B/D 为非 null 时照抄、为 null 时你来补全；C 仅是启发式线索，由你用世界知识最终定分）：",
        "",
        "```json",
        json.dumps(metrics_list, ensure_ascii=False, indent=2),
        "```",
        "",
        f"请调用 {TOOL_NAME} 工具提交评分，results 与上面候选词一一对应。",
    ]
    return "\n".join(lines)
